#!/usr/bin/env python3
"""Road map "creator-jobs" CU9a — Clip ▸ Retime Range… and `retime_range`
(spec §11 CU-90).

    python3 tools/proof/retime_proof.py [SOCKET] [--only R2,R5,…] [--mutant NAME] [--app PATH]

SOCKET is a running instance's `<dir>/agent.sock` (`proof_app.py launch`);
without it the plain rows launch their own instance. R9 always launches its
own, with `-RCDevRetimeAccept YES`. Launches run on a scratch
`CFFIXED_USER_HOME`; packages and media are made under
`tools/proof/work/retime-proof/`. The media are generated by ffmpeg: a 20 s
640 × 360 30 fps screen (`testsrc`, no sound), a 20 s camera (`testsrc2` and
a 440 Hz tone) and a 20 s microphone (a 660 Hz tone).

Rows:
- R1 `cd core && cargo test --release --test retime_range` passes (every
  refusal in order, sync across three tracks, the marker rule).
- R2 F1 (screen, microphone and camera at 0 on three tracks, the camera at
  half scale), retimed ×4 over [5 s, 15 s): the project is 7.5 s shorter;
  `prores_422` exports before and after decoded to rgb24, frame `to′` after
  (7.5 s) has the md5 of frame `to` before (15 s); `render_frame` at 7.5 s
  after is byte-equal to `render_frame` at 15 s before.
- R4 then one `undo` names "Retime Range" and gives back `get_project`'s
  project exactly.
- R5 the camera's sound detached, then a retime over it refused in AU-94's
  sentence naming the picture and its sound; the project unchanged.
- R6 the screen at ×300 (two frames) sped ×4: refused naming ×1200.
- R7 F1's three clips nested, two markers 1 frame apart at 5 s: `scope` on
  the nest retimes its tracks (a 2.5 s piece at 5 s) and the markers stay.
- R8a, R8b, R9p `retime_probe.swift` (built with `swift_build.build()`): the
  sheet's question on its own window, Cancel and Set Speed; a ×2 control
  that asks nothing; the sheet's Keep pitch equal to `keep_pitch: false`.
- R9 on an instance launched with `-RCDevRetimeAccept YES`: the camera with
  Keep pitch off and the microphone with it on, In–Out [5 s, 15 s);
  Clip ▸ Retime Range… by `perform_menu_item` gives one step "Retime Range"
  whose project equals `retime_range {rate: 2, keep_pitch: false}`'s over
  the same range after an undo.
- R10 the camera (sound) at ×4, `retime_range` ×4 over [1 s, 3 s):
  `audio_left_out` is exactly the new piece at 1 s, and `audio_note` is the
  one-clip sentence for it, word for word.
- Z1 `grep "Frame Job: "` of every instance's log prints nothing.

`--mutant NAME`: the named decision broken in a `tree_copy.py` copy; its
probe rows build from the copy's `app/Sources`, its MCP rows run on the
copy's built app. CAUGHT exits 1 (a named row failed), SURVIVED exits 0, a
control that could not be performed exits 2.
"""

